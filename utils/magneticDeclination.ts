/**
 * 磁気偏角（磁北が真北からどれだけ東へずれているか。西偏は負）の簡易テーブル。
 *
 * 端末のコンパスは磁北基準、距離・方位の計算は真北基準のため、その差を補正するのに使う。
 * WMM（World Magnetic Model）から 2026-10 時点で生成した値を、日本周辺の 2° グリッドに
 * 焼き込んでいる。偏角の経年変化は年 0.1° 前後なので、数年はそのまま使える。
 * グリッドの外側（日本周辺以外）では補正しない（0 を返す）。
 */
const LAT0 = 24;
const LON0 = 122;
const STEP = 2;

// GRID[緯度インデックス][経度インデックス]  緯度 24〜46°N / 経度 122〜146°E
const GRID: number[][] = [
  [-4.9, -5.1, -5.2, -5.3, -5.3, -5.2, -5, -4.8, -4.5, -4.1, -3.7, -3.2, -2.7],
  [-5.3, -5.6, -5.7, -5.8, -5.8, -5.8, -5.6, -5.4, -5.1, -4.7, -4.3, -3.8, -3.3],
  [-5.8, -6.1, -6.3, -6.4, -6.4, -6.3, -6.2, -6, -5.7, -5.4, -5, -4.5, -4],
  [-6.3, -6.6, -6.8, -6.9, -7, -6.9, -6.8, -6.6, -6.4, -6, -5.6, -5.2, -4.7],
  [-6.8, -7.1, -7.4, -7.5, -7.6, -7.5, -7.4, -7.3, -7, -6.7, -6.3, -5.9, -5.4],
  [-7.4, -7.7, -7.9, -8.1, -8.1, -8.1, -8.1, -7.9, -7.7, -7.3, -7, -6.5, -6],
  [-7.9, -8.2, -8.5, -8.6, -8.7, -8.8, -8.7, -8.5, -8.3, -8, -7.6, -7.2, -6.7],
  [-8.4, -8.8, -9, -9.2, -9.3, -9.4, -9.3, -9.1, -8.9, -8.6, -8.3, -7.8, -7.4],
  [-9, -9.3, -9.6, -9.8, -9.9, -10, -9.9, -9.8, -9.5, -9.2, -8.9, -8.5, -8],
  [-9.5, -9.9, -10.2, -10.4, -10.5, -10.6, -10.5, -10.4, -10.1, -9.9, -9.5, -9.1, -8.6],
  [-10.1, -10.5, -10.8, -11, -11.1, -11.1, -11.1, -11, -10.7, -10.5, -10.1, -9.7, -9.2],
  [-10.7, -11.1, -11.4, -11.6, -11.7, -11.7, -11.7, -11.5, -11.3, -11, -10.7, -10.3, -9.8],
];

export function getMagneticDeclination(lat: number, lon: number): number {
  const fi = (lat - LAT0) / STEP;
  const fj = (lon - LON0) / STEP;
  const maxI = GRID.length - 1;
  const maxJ = GRID[0].length - 1;
  if (!(fi >= 0 && fi <= maxI && fj >= 0 && fj <= maxJ)) return 0;

  const i0 = Math.min(Math.floor(fi), maxI - 1);
  const j0 = Math.min(Math.floor(fj), maxJ - 1);
  const ti = fi - i0;
  const tj = fj - j0;

  const top = GRID[i0][j0] * (1 - tj) + GRID[i0][j0 + 1] * tj;
  const bottom = GRID[i0 + 1][j0] * (1 - tj) + GRID[i0 + 1][j0 + 1] * tj;
  return top * (1 - ti) + bottom * ti;
}
